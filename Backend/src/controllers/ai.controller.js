import Incident from "../models/incident.model.js";
import Timeline from "../models/timeline.model.js";
import { createNotification } from "../utils/notification.util.js";
import { getIO } from "../socket/index.js";

export const analyzeIncident = async (req, res) => {
  try {
    const { incidentId } = req.body;

    const incident = await Incident.findById(incidentId);

    if (!incident) {
      return res.status(404).json({
        success: false,
        message: "Incident not found"
      });
    }

    if (incident.status === "resolved") {
      return res.status(400).json({
        success: false,
        message: "Cannot run AI on resolved incident"
      });
    }

    const userId = req.user._id.toString();

    const isLead = incident.assignedLead.toString() === userId;
    const isResponder = incident.responders
      .map(id => id.toString())
      .includes(userId);

    if (!isLead && !isResponder) {
      return res.status(403).json({
        success: false,
        message: "Not authorized to run AI"
      });
    }

    const timeline = await Timeline.find({ incident: incidentId })
      .sort({ createdAt: 1 });

    if (timeline.length === 0) {
      return res.status(400).json({
        success: false,
        message: "No timeline data for AI analysis"
      });
    }

    const timelineText = timeline
      .map(t => `${new Date(t.createdAt).toLocaleTimeString()} - ${t.message}`)
      .join("\n");

    const context = `
    Title: ${incident.title}
    Description: ${incident.description}
    Severity: ${incident.severity}
    Timeline: ${timelineText}
    `;

    const aiResponse = {
      nextAction: "Restart service and monitor logs",
      timelineSummary: timelineText,
      rootCause: "Possible memory leak in backend service",
      impact: "API downtime for users",
      resolution: "Service restarted and fix deployed"
    };

    incident.aiSuggestions = {
      nextAction: aiResponse.nextAction,
      timelineSummary: aiResponse.timelineSummary,
      generatedBy: req.user._id,
      generatedAt: new Date()
    };

    if (!incident.postmortem?.rootCause) {
      incident.postmortem = {
        summary: aiResponse.timelineSummary,
        rootCause: aiResponse.rootCause,
        impact: aiResponse.impact,
        resolution: aiResponse.resolution
      };
    }

    await incident.save();

    await Timeline.create({
      incident: incident._id,
      message: `AI suggestions generated by ${req.user.username}`,
      type: "ai",
      createdBy: req.user._id
    });

    const recipients = [
      incident.assignedLead,
      ...incident.responders
    ]
    .map(id => id.toString())
    .filter(id => id !== userId);

    const uniqueRecipients = [...new Set(recipients)];

    await createNotification({
      recipients: uniqueRecipients,
      message: "AI suggestions generated for incident",
      incidentId: incident._id,
      type: "aiGenerated"
    });

    const io = getIO();
    uniqueRecipients.forEach(userId => {
      io.to(userId).emit("ai_generated", {
        incidentId: incident._id,
        message: "AI suggestions generated"
      });
    });

    return res.status(200).json({
      success: true,
      data: incident.aiSuggestions
    });

  } catch (err) {
    return res.status(500).json({
      success: false,
      message: err.message
    });
  }
};